#!/usr/bin/env python3
"""Generate tokens.css, tailwind.theme.css and tokens.dark.json from tokens.json.

    python3 replica/design/build_tokens.py --out replica/design --out app/src/styles

tokens.json is the only file you edit. replica-brand changes values there and
reruns this. Then check both themes:

    python3 ~/.claude/skills/replica-design/contrast.py replica/design/tokens.json
    python3 ~/.claude/skills/replica-design/contrast.py replica/design/tokens.dark.json
"""
import argparse, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = "/* GENERATED by build_tokens.py from tokens.json. Do not edit by hand. */\n"


def css_vars(colors, indent="  "):
    return "".join(f"{indent}--t-color-{k}: {v};\n" for k, v in colors.items())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=os.path.join(HERE, "tokens.json"))
    ap.add_argument("--out", action="append", help="output dir (repeatable); default: next to tokens.json")
    a = ap.parse_args()
    outs = a.out or [HERE]
    t = json.load(open(a.src))
    light, dark = t["color"], t["color_dark"]
    assert set(light) == set(dark), "light and dark must define the same roles: %s" % (set(light) ^ set(dark))

    root = [":root {\n", "  color-scheme: light;\n", css_vars(light)]
    root.append(f"  --t-font-sans: {t['font']['sans']};\n  --t-font-mono: {t['font']['mono']};\n")
    for k, v in t["type"].items():
        root.append(f"  --t-text-{k}: {v['size']/16:g}rem;\n  --t-text-{k}-line: {v['line']/16:g}rem;\n"
                    f"  --t-text-{k}-weight: {v['weight']};\n")
    for i, v in enumerate(t["space"]):
        root.append(f"  --t-space-{i}: {v}px;\n")
    for k, v in t["radius"].items():
        root.append(f"  --t-radius-{k}: {v}px;\n")
    for k, v in t["shadow"].items():
        root.append(f"  --t-shadow-{k}: {v};\n")
    root.append(f"  --t-motion-fast: {t['motion']['fast']};\n  --t-motion-base: {t['motion']['base']};\n"
                f"  --t-motion-ease: {t['motion']['ease']};\n")
    for density in ("compact", "touch"):
        for k, v in t["control"][density].items():
            root.append(f"  --t-control-{density}-{k}: {v}px;\n")
    for k, v in t["layout"].items():
        if isinstance(v, (int, float)):
            root.append(f"  --t-layout-{k}: {v}px;\n")
    root.append("}\n\n")

    # Density: [data-density=touch] swaps control heights for POS/captain/KDS/kiosk surfaces.
    root.append(":root, [data-density=compact] {\n" + "".join(
        f"  --t-control-{k}: var(--t-control-compact-{k});\n" for k in t["control"]["compact"]) + "}\n")
    root.append("[data-density=touch] {\n" + "".join(
        f"  --t-control-{k}: var(--t-control-touch-{k});\n" for k in t["control"]["touch"]) + "}\n\n")

    dark_block = "  color-scheme: dark;\n" + css_vars(dark, "    ")
    root.append("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=light]) {\n"
                + dark_block.replace("  color-scheme", "    color-scheme", 1) + "  }\n}\n")
    root.append("[data-theme=dark] {\n  color-scheme: dark;\n" + css_vars(dark) + "}\n")
    root.append("[data-theme=light] {\n  color-scheme: light;\n" + css_vars(light) + "}\n")
    for o in outs:
        open(os.path.join(o, "tokens.css"), "w").write(HEADER + "".join(root))

    # Tailwind v4: map roles into the theme so components write bg-surface, text-muted, rounded-md...
    tw = [HEADER, "@theme inline {\n",
          "  /* roles only: Tailwind's default palette is switched off so no raw colours sneak in */\n",
          "  --color-*: initial;\n  --color-transparent: transparent;\n  --color-current: currentColor;\n"]
    tw += [f"  --color-{k}: var(--t-color-{k});\n" for k in light]
    tw.append("  --font-sans: var(--t-font-sans);\n  --font-mono: var(--t-font-mono);\n")
    for k in t["type"]:
        tw.append(f"  --text-{k}: var(--t-text-{k});\n  --text-{k}--line-height: var(--t-text-{k}-line);\n"
                  f"  --text-{k}--font-weight: var(--t-text-{k}-weight);\n")
    tw += [f"  --radius-{k}: var(--t-radius-{k});\n" for k in t["radius"]]
    tw += [f"  --shadow-{k}: var(--t-shadow-{k});\n" for k in t["shadow"]]
    tw += [f"  --spacing-control-{k}: var(--t-control-{k});\n" for k in t["control"]["compact"]]
    for k, v in t["layout"]["breakpoints"].items():
        tw.append(f"  --breakpoint-{k}: {v/16:g}rem;\n")
    tw.append("}\n")
    for o in outs:
        open(os.path.join(o, "tailwind.theme.css"), "w").write("".join(tw))

    json.dump({"_about": "GENERATED from tokens.json color_dark, for contrast.py only.",
               "color": dark, "pairs": t["pairs"]},
              open(os.path.join(HERE, "tokens.dark.json"), "w"), indent=1)
    print("wrote tokens.css, tailwind.theme.css, tokens.dark.json (%d roles)" % len(light))


if __name__ == "__main__":
    main()
